function t(string $key): string
{
    global $lang, $translations;

    if (!isset($translations[$lang][$key])) {
        throw new OutOfBoundsException('Missing translation: ' . $key);
    }

    return htmlspecialchars($translations[$lang][$key], ENT_QUOTES | ENT_SUBSTITUTE, 'UTF-8');
}
